import { HEALTH_LABELS, STATUS_LABELS, type ProjectHealth, type ProjectStatus } from "./project-lifecycle";

type Metrics = {
  asOf?: string;
  milestones?: {
    overdue?: { name: string; dueDate: string }[];
    dueNext14Days?: { name: string; dueDate: string }[];
    achievedInPeriod?: { name: string; completedOn: string | null }[];
    slipped?: { name: string; varianceDays: number | null }[];
  };
  sprint?: { name: string; endDate: string; committedPoints: number; scopePoints: number; donePoints: number } | null;
  blockedItems?: number;
  completedItems?: number;
  changes?: { change_type: string; from_status: ProjectStatus | null; to_status: ProjectStatus | null; from_health: ProjectHealth | null; to_health: ProjectHealth | null; reason: string | null }[];
};

export type ReportForMarkdown = {
  projectCode: string;
  projectName: string;
  periodStart: string;
  periodEnd: string;
  health: ProjectHealth;
  summary: string;
  highlights: string | null;
  nextSteps: string | null;
  decisionsNeeded: string | null;
  metrics: Metrics;
};

/** Plain Markdown version of a status report, for pasting into email, Teams or Slack. */
export function reportToMarkdown(r: ReportForMarkdown): string {
  const m = r.metrics;
  const lines: string[] = [
    `## ${r.projectCode} · ${r.projectName} — status ${r.periodStart} to ${r.periodEnd}`,
    "",
    `**Health:** ${HEALTH_LABELS[r.health]}`,
    "",
    r.summary,
  ];
  const section = (title: string, body: string | null | undefined) => {
    if (body && body.trim()) lines.push("", `### ${title}`, body.trim());
  };
  section("Highlights", r.highlights);
  section("Next steps", r.nextSteps);
  section("Decisions needed", r.decisionsNeeded);

  lines.push("", "### Evidence");
  const list = (items: string[]) => (items.length ? items.map((i) => `- ${i}`) : ["- None"]);
  lines.push("**Overdue milestones**", ...list((m.milestones?.overdue ?? []).map((x) => `${x.name} (due ${x.dueDate})`)));
  lines.push("**Due in the next 14 days**", ...list((m.milestones?.dueNext14Days ?? []).map((x) => `${x.name} (${x.dueDate})`)));
  lines.push("**Achieved this period**", ...list((m.milestones?.achievedInPeriod ?? []).map((x) => `${x.name} (${x.completedOn})`)));
  const slipped = m.milestones?.slipped ?? [];
  if (slipped.length) lines.push("**Slipped against baseline**", ...list(slipped.map((x) => `${x.name} (+${x.varianceDays} days)`)));
  if (m.sprint) {
    lines.push(`**Sprint:** ${m.sprint.name} — ${m.sprint.donePoints} of ${m.sprint.scopePoints} points done (committed ${m.sprint.committedPoints}), ends ${m.sprint.endDate}`);
  }
  lines.push(`**Work items completed this period:** ${m.completedItems ?? 0} · **Blocked now:** ${m.blockedItems ?? 0}`);
  const changes = (m.changes ?? []).map((c) =>
    c.change_type === "status"
      ? `Status ${STATUS_LABELS[c.from_status!]} → ${STATUS_LABELS[c.to_status!]}${c.reason ? `: ${c.reason}` : ""}`
      : `Health ${HEALTH_LABELS[c.from_health!]} → ${HEALTH_LABELS[c.to_health!]}${c.reason ? `: ${c.reason}` : ""}`,
  );
  if (changes.length) lines.push("**Changes this period**", ...list(changes));
  lines.push("", `_Evidence as of ${m.asOf ?? r.periodEnd}, generated by Stride._`);
  return lines.join("\n");
}
