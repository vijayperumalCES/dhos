"use client";

import { useRouter } from "next/navigation";
import { useEffect, useState, useTransition } from "react";

import { Button } from "@/components/ui/button";
import { Field, FieldDescription, FieldError, FieldLabel } from "@/components/ui/field";
import { Input } from "@/components/ui/input";
import { signOut } from "@/lib/actions/auth";
import { createSupabaseBrowserClient } from "@/lib/supabase/browser";

type Enrollment = { factorId: string; qr: string; secret: string };

/**
 * TOTP step-up. With a verified authenticator the person types a code; otherwise they enrol one
 * first (scan the QR code, then confirm with a code). Either way the session ends up at aal2.
 */
export function MfaForm() {
  const router = useRouter();
  const [supabase] = useState(() => createSupabaseBrowserClient());
  const [factorId, setFactorId] = useState<string | null>(null);
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [loading, setLoading] = useState(true);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [pending, startTransition] = useTransition();

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const { data: factors, error: listError } = await supabase.auth.mfa.listFactors();
      if (cancelled) return;
      if (listError) {
        setError("Could not load your authenticator settings. Check that multi-factor authentication is enabled for this project.");
        setLoading(false);
        return;
      }
      const verified = factors?.totp.find((f) => f.status === "verified");
      if (verified) {
        setFactorId(verified.id);
        setLoading(false);
        return;
      }
      // Drop abandoned, never-verified enrolments so they don't pile up.
      for (const f of factors?.all ?? []) if (f.status === "unverified") await supabase.auth.mfa.unenroll({ factorId: f.id });
      const { data, error: enrollError } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: "Authenticator app" });
      if (cancelled) return;
      if (enrollError || !data) setError("Could not start enrolment. Check that multi-factor authentication is enabled for this project.");
      else {
        setFactorId(data.id);
        setEnrollment({ factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
      }
      setLoading(false);
    })();
    return () => {
      cancelled = true;
    };
  }, [supabase]);

  function verify() {
    if (!factorId) return;
    startTransition(async () => {
      setError(null);
      const { error: verifyError } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
      if (verifyError) {
        setError("That code didn't work. Check the code in your app and try again.");
        return;
      }
      router.replace("/");
      router.refresh();
    });
  }

  if (loading) return <p className="text-sm text-muted-foreground">Loading…</p>;

  return (
    <form
      noValidate
      className="space-y-4"
      onSubmit={(e) => {
        e.preventDefault();
        verify();
      }}
    >
      {enrollment && (
        <div className="space-y-3 rounded-md border p-4 text-sm">
          <p className="font-medium">Set up an authenticator app</p>
          <p className="text-muted-foreground">Scan this code with an app such as Microsoft Authenticator, Google Authenticator or 1Password.</p>
          {/* The QR code is a data: URI generated by Supabase Auth for this enrolment only. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={enrollment.qr} alt="QR code for your authenticator app" className="size-44 rounded bg-white p-2" />
          <p className="text-muted-foreground">
            Can&apos;t scan? Enter this key instead: <code className="font-mono break-all">{enrollment.secret}</code>
          </p>
        </div>
      )}
      <Field data-invalid={!!error}>
        <FieldLabel htmlFor="mfa-code">6-digit code</FieldLabel>
        <Input
          id="mfa-code"
          inputMode="numeric"
          autoComplete="one-time-code"
          maxLength={6}
          value={code}
          onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
          aria-invalid={!!error}
          autoFocus
        />
        {error ? <FieldError>{error}</FieldError> : <FieldDescription>Open your authenticator app and enter the current code.</FieldDescription>}
      </Field>
      <Button type="submit" className="w-full" disabled={pending || code.length !== 6 || !factorId}>
        {pending ? "Verifying…" : "Verify"}
      </Button>
      <Button type="button" variant="ghost" className="w-full" onClick={() => startTransition(() => signOut())}>
        Sign out
      </Button>
    </form>
  );
}
